import fs from "fs";
import path from "path";
import { assertAllQuizzesExist, getAllQuizzesFromMdx } from "../src/lib/quizzes/quizParser";
import { assertLocaleIdParity } from "./lib/validateLocaleParity";

async function main() {
  await assertAllQuizzesExist("en");
  await assertAllQuizzesExist("es");
  const en = await getAllQuizzesFromMdx("en");
  const es = await getAllQuizzesFromMdx("es");

  assertLocaleIdParity(en, es, "quizzes");

  const dataDir = path.join(process.cwd(), "src", "data");
  const header = `// Auto-generated by scripts/bundle-quizzes.ts — do not edit by hand.\n// Edit content/quizzes/{en,es}/*.mdx then run: npm run content:bundle-quizzes\n\nimport type { Quiz } from "@/types/quiz";\n\n`;
  const combinedHeader = `// Auto-generated by scripts/bundle-quizzes.ts — do not edit by hand.\n// Edit content/quizzes/{en,es}/*.mdx then run: npm run content:bundle-quizzes\n// Server/SSG only. Do not import this combined barrel from 'use client' modules.\n// Client code must dynamic-import ./quizBundles.en or ./quizBundles.es.\n\nimport type { Quiz } from "@/types/quiz";\n\n`;

  const writeLocaleBundle = (locale: "en" | "es", quizzes: typeof en) => {
    const outPath = path.join(dataDir, `quizBundles.${locale}.ts`);
    fs.writeFileSync(
      outPath,
      `${header}export const quizzes: Quiz[] = ${JSON.stringify(quizzes, null, 2)} as const;\n`,
      "utf8"
    );
    return outPath;
  };

  writeLocaleBundle("en", en);
  writeLocaleBundle("es", es);

  const indexPath = path.join(dataDir, "quizBundles.ts");
  fs.writeFileSync(
    indexPath,
    `${combinedHeader}import { quizzes as en } from "./quizBundles.en";\nimport { quizzes as es } from "./quizBundles.es";\n\nexport const quizBundles: Record<"en" | "es", Quiz[]> = { en, es } as const;\n`,
    "utf8"
  );

  console.log(`Wrote quiz bundles (${en.length} EN, ${es.length} ES quizzes).`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
